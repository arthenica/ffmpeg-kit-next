import 'dart:js_interop';

import 'package:web/web.dart' as web;

void writeLogOutput(String text) {
  final line = text.endsWith('\n') ? text.substring(0, text.length - 1) : text;
  if (line.isNotEmpty) web.console.log(line.toJS);
}
